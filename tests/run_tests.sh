#!/bin/sh
# Builds every test program, recompiles it and checks that the recompiled
# program behaves exactly like the original (same stdout, same exit code).
#   sh tests/run_tests.sh                 # Linux musl (fast, ~1 min)
#   TARGETS="musl win" sh tests/run_tests.sh
#   TARGETS="musl glibc win" sh tests/run_tests.sh   # glibc is ~3 min per program
#   TARGETS="win win32" sh tests/run_tests.sh        # Windows, 64-bit and 32-bit
# win needs: x86_64-w64-mingw32-gcc and wine; win32 needs: i686-w64-mingw32-gcc and wine
set -u
cd "$(dirname "$0")"
ROOT=..
OUT=${OUT:-/tmp/recomp_tests}
TARGETS=${TARGETS:-musl}
mkdir -p "$OUT"
pass=0; fail=0

check() {  # name binary [extra args for recomp.py]
    name=$1; bin=$2; shift 2
    if python3 $ROOT/recomp.py all "$bin" -o "$OUT/$name" "$@" > "$OUT/$name.log" 2>&1; then
        echo "PASS  $name"; pass=$((pass + 1))
    else
        echo "FAIL  $name   (see $OUT/$name.log and $OUT/$name/logs/)"; fail=$((fail + 1))
    fi
}

# instruction families (tests/isa.c): lift + build once, then every family must
# print the same checksum as the original, with the CPU features the runtime
# reports in RECOMP_CPUID=verified mode
ISA_FAMILIES="int string x87 ssse3 sse41 sse42 bmi adx movbe aes sha avx avx2 fma f16c"
check_isa() {  # name binary
    name=$1; bin=$2
    if ! { python3 $ROOT/recomp.py lift "$bin" -o "$OUT/$name" && python3 $ROOT/recomp.py build "$OUT/$name"; } \
            > "$OUT/$name.log" 2>&1; then
        echo "FAIL  $name   (lift/build, see $OUT/$name.log)"; fail=$((fail + 1)); return
    fi
    for f in $ISA_FAMILIES; do
        if RECOMP_CPUID=verified python3 $ROOT/recomp.py verify "$bin" "$OUT/$name" -- $f >> "$OUT/$name.log" 2>&1; then
            echo "PASS  $name $f"; pass=$((pass + 1))
        else
            echo "FAIL  $name $f   (see $OUT/$name.log)"; fail=$((fail + 1))
        fi
    done
}

# tests/avx_wide.c (generated by gen_avx_test.py): ~690 AVX/AVX2/VEX intrinsics,
# one checksum line each; the whole output must be identical
check_wide() {  # name binary
    name=$1; bin=$2
    if { python3 $ROOT/recomp.py lift "$bin" -o "$OUT/$name" && python3 $ROOT/recomp.py build "$OUT/$name"; } \
            > "$OUT/$name.log" 2>&1 &&
       RECOMP_CPUID=verified python3 $ROOT/recomp.py verify "$bin" "$OUT/$name" -- all >> "$OUT/$name.log" 2>&1; then
        echo "PASS  $name ($(grep -c . "$OUT/$name/logs/stdout.original" 2>/dev/null || echo '?') lines)"; pass=$((pass + 1))
    else
        echo "FAIL  $name   (see $OUT/$name.log)"; fail=$((fail + 1))
    fi
}

for target in $TARGETS; do
    case $target in
    musl|glibc)
        if [ $target = musl ]; then CC="musl-gcc"; else CC="gcc"; fi
        for t in hello algo floats fileio game crashes; do
            $CC -static -no-pie -O2 -o ${t}_$target $t.c -lm || exit 1
        done
        check hello_$target   hello_$target   -- one "two words"
        check algo_$target    algo_$target    -- 20000
        check floats_$target  floats_$target
        check fileio_$target  fileio_$target  --stdin input.txt
        check game_$target    game_$target
        check crashes_$target crashes_$target -- null   # both must crash the same way
        check aes_$target     crashes_$target -- aes
        $CC -static -no-pie -O2 -o isa_$target isa.c -lm || exit 1
        check_isa isa_$target isa_$target
        $CC -static -no-pie -O2 -o avx_wide_$target avx_wide.c || exit 1
        check_wide avx_wide_$target avx_wide_$target
        ;;
    win)
        CC=x86_64-w64-mingw32-gcc
        for t in hello algo floats wintest; do $CC -O2 -o ${t}_win.exe $t.c -lm || exit 1; done
        check hello_win   hello_win.exe   -- one "two words"
        check algo_win    algo_win.exe    -- 20000
        check floats_win  floats_win.exe
        check wintest_win wintest_win.exe
        $CC -O2 -o isa_win.exe isa.c -lm || exit 1
        check_isa isa_win isa_win.exe
        $CC -O2 -o avx_wide_win.exe avx_wide.c || exit 1
        check_wide avx_wide_win avx_wide_win.exe
        ;;
    win32)  # 32-bit Windows programs (rebuilt as 32-bit programs)
        CC=i686-w64-mingw32-gcc
        for t in hello algo floats wintest; do $CC -O2 -o ${t}_win32.exe $t.c -lm || exit 1; done
        # the same program without a relocation table, like most old 32-bit exes
        $CC -O2 -o wintest_norel32.exe wintest.c -lm -Wl,--disable-dynamicbase -Wl,--disable-reloc-section || exit 1
        check hello_win32   hello_win32.exe   -- one "two words"
        check algo_win32    algo_win32.exe    -- 20000
        check floats_win32  floats_win32.exe
        check wintest_win32 wintest_win32.exe
        check wintest_norel32 wintest_norel32.exe
        # 64-bit math, SSE2, MMX, x87, CMPXCHG8B, static TLS
        $CC -O2 -msse2 -o cpu32.exe cpu32.c -lm || exit 1
        check cpu32 cpu32.exe
        $CC -O2 -o isa_win32.exe isa.c -lm || exit 1
        check_isa isa_win32 isa_win32.exe
        $CC -O2 -o avx_wide_win32.exe avx_wide.c || exit 1
        check_wide avx_wide_win32 avx_wide_win32.exe
        ;;
    esac
done
echo "$pass passed, $fail failed"
[ $fail -eq 0 ]
